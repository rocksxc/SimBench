"""Sequential annotation designs: an item gets a first batch of votes and, depending on the votes so far,
further batches.  The observable law is the law of the terminal (agree, disagree) pair; given pi it is
mult(a,b) * pi^a (1-pi)^b.  Identified sets are again linear programs."""
import numpy as np
from math import comb
from scipy.optimize import linprog
import fewannot as fa

def terminal_nodes(batches, cont):
    """batches: list of batch sizes; cont(stage, a, b) -> True if the item continues after `stage` batches.
    Returns dict {(a, b): multiplicity} over terminal nodes (path-counting multiplicities)."""
    live = {(0, 0): 1}; term = {}
    for s, k in enumerate(batches):
        new = {}
        for (a, b), mult in live.items():
            for j in range(k + 1):
                key = (a + j, b + k - j); new[key] = new.get(key, 0) + mult * comb(k, j)
        live = {}
        for key, mult in new.items():
            if s + 1 < len(batches) and cont(s + 1, *key):
                live[key] = mult
            else:
                term[key] = term.get(key, 0) + mult
    return term

def design_matrix(term, xs):
    keys = sorted(term)
    with np.errstate(divide="ignore", invalid="ignore"):
        A = np.array([term[(a, b)] * np.where(a > 0, xs ** a, 1.0) * np.where(b > 0, (1 - xs) ** b, 1.0) for a, b in keys])
    return keys, A

def idset_design(pis, w, term, f, xs):
    """Bounds on int f dH over H matching the terminal law generated by the discrete law (pis, w)."""
    keys, A = design_matrix(term, xs)
    _, A0 = design_matrix(term, np.asarray(pis))
    q = A0 @ np.asarray(w)
    cost = sum(qq * (a + b) for qq, (a, b) in zip(q, keys))
    return fa._lp(f, A, q), -fa._lp(-f, A, q), cost

if __name__ == "__main__":
    rng = np.random.default_rng(3)
    N = 200000
    pi = np.where(rng.random(N) < 0.7, rng.beta(0.5, 6, N), rng.beta(2.2, 2.2, N))
    pi = np.where(rng.random(N) < 0.5, 1 - pi, pi)
    yhat = (pi + rng.normal(0, 0.10, N) > 0.5)
    x = np.where(yhat, pi, 1 - pi)                       # agreement share
    bins = np.linspace(0, 1, 1001); mid = (bins[:-1] + bins[1:]) / 2; w = np.histogram(x, bins)[0] / N
    xs, above, below = fa.make_grid(0.5)
    f = above.astype(float)
    print(f"consensus agreement {np.mean(x > 0.5):.4f}")
    print("fixed panels")
    for n in (3, 5, 7, 9, 11, 15):
        lo, hi, c = idset_design(mid, w, terminal_nodes([n], None), f, xs)
        print(f"  n={n:2d}  votes/item {c:5.2f}  set [{lo:.4f},{hi:.4f}] width {hi-lo:.4f}")
    print("top-up: 3 votes for all, then extra votes while the margin is small")
    for name, batches, rule in [
        ("3 + 4 if not unanimous", [3, 4], lambda s, a, b: min(a, b) > 0),
        ("3 + 6 if not unanimous", [3, 6], lambda s, a, b: min(a, b) > 0),
        ("3 + 12 if not unanimous", [3, 12], lambda s, a, b: min(a, b) > 0),
        ("3 + 4 + 8 while margin <= 3", [3, 4, 8], lambda s, a, b: abs(a - b) <= 3 and min(a, b) > 0),
        ("5 + 10 if margin <= 3", [5, 10], lambda s, a, b: abs(a - b) <= 3),
        ("3 + 6 + 12 while margin <= 3", [3, 6, 12], lambda s, a, b: abs(a - b) <= 3),
    ]:
        lo, hi, c = idset_design(mid, w, terminal_nodes(batches, rule), f, xs)
        print(f"  {name:32s} votes/item {c:5.2f}  set [{lo:.4f},{hi:.4f}] width {hi-lo:.4f}")
